package webaccess

import (
	"crypto/x509"
	"fmt"
	"net"
	"net/netip"
	"net/url"
	"strings"
	"time"
)

// Check is one line of the result list. Status is ok, warning, error or info.
type Check struct {
	Status string `json:"status"`
	Title  string `json:"title"`
	Detail string `json:"detail,omitempty"`
}

// HasError reports whether any check failed.
func HasError(cs []Check) bool {
	for _, c := range cs {
		if c.Status == "error" {
			return true
		}
	}
	return false
}

// CheckEnv is what validation needs to know about the world.
type CheckEnv struct {
	Now time.Time
	// OwnCertPEM and OwnKeyPEM are a certificate uploaded with this request.
	OwnCertPEM, OwnKeyPEM []byte
	// InUse reports whether this controller already listens on addr (then a
	// bind test would only fail against ourselves).
	InUse func(addr string) bool
	// Bind tries to listen on addr and gives it back. Nil uses the network.
	Bind func(addr string) error
	// Peer and ForwardedProto describe the request that asks for the check:
	// its direct peer and its X-Forwarded-Proto header ("" if none).
	Peer           netip.Addr
	ForwardedProto string
	Host           string // the Host header the admin used, to build the new address
}

func netBind(addr string) error {
	l, err := net.Listen("tcp", addr)
	if err != nil {
		return err
	}
	return l.Close()
}

// Validate checks a normalised proposal. A check with status error blocks
// applying it; warnings and info do not.
func Validate(s Settings, env CheckEnv) []Check {
	var cs []Check
	add := func(status, title, detail string, a ...any) {
		cs = append(cs, Check{Status: status, Title: title, Detail: fmt.Sprintf(detail, a...)})
	}
	if env.Now.IsZero() {
		env.Now = time.Now()
	}
	switch s.Mode {
	case ModeOff, ModeSelfSigned, ModeOwn, ModeACME, ModeProxy:
	default:
		add("error", "Mode", "%q is not a mode", s.Mode)
		return cs
	}

	// Public URL.
	var pub *url.URL
	if s.PublicURL != "" {
		u, err := ParsePublicURL(s.PublicURL)
		if err != nil {
			add("error", "Public URL", "%v", err)
		} else {
			pub = u
			if s.IsTLS() && u.Scheme != "https" {
				add("error", "Public URL", "must start with https:// in this mode")
			} else {
				add("ok", "Public URL", "%s", s.PublicURL)
			}
		}
	}

	// Listeners.
	httpAddr := s.Listen
	if s.IsTLS() {
		httpAddr = ""
	}
	addrs := []struct{ label, addr string }{}
	if s.IsTLS() {
		addrs = append(addrs, struct{ label, addr string }{"HTTPS address", s.HTTPSListen})
		if s.HTTPRedirect != "" {
			addrs = append(addrs, struct{ label, addr string }{"HTTP redirect address", s.HTTPRedirect})
		}
		if s.HTTPRedirect != "" && s.HTTPRedirect == s.HTTPSListen {
			add("error", "HTTP redirect address", "must differ from the HTTPS address")
		}
	} else {
		addrs = append(addrs, struct{ label, addr string }{"HTTP address", httpAddr})
	}
	bind := env.Bind
	if bind == nil {
		bind = netBind
	}
	for _, a := range addrs {
		if _, _, err := SplitAddr(a.addr); err != nil {
			add("error", a.label, "%v", err)
			continue
		}
		switch {
		case env.InUse != nil && env.InUse(a.addr):
			add("ok", a.label, "%s is already served by this controller", a.addr)
		default:
			if err := bind(a.addr); err != nil {
				add("error", a.label, "cannot listen on %s: %v", a.addr, err)
			} else {
				add("ok", a.label, "%s can be bound", a.addr)
			}
		}
	}
	if !s.IsTLS() && !isLoopbackAddr(s.Listen) && s.Mode == ModeOff {
		add("warning", "Sign-ins travel unencrypted", "%s accepts connections from the network over plain HTTP", s.Listen)
	}

	switch s.Mode {
	case ModeOff:
		if s.HSTS {
			add("warning", "HSTS", "has no effect while the controller serves plain HTTP")
		}
	case ModeSelfSigned:
		if len(s.Names) == 0 {
			add("error", "Names", "list at least one host name or IP address for the certificate")
		}
		for _, n := range s.Names {
			if !ValidName(n) {
				add("error", "Names", "%q is not a host name or IP address", n)
			}
		}
		if pub != nil && !listed(s.Names, pub.Hostname()) {
			add("warning", "Names", "the public URL host %s is not in the list; browsers will show a name mismatch", pub.Hostname())
		}
		add("info", "Certificate", "generated by the controller, valid 825 days, trusted by nobody until you accept its fingerprint")
	case ModeOwn:
		cs = append(cs, ownChecks(s, env, pub)...)
	case ModeACME:
		cs = append(cs, acmeChecks(s, pub)...)
	case ModeProxy:
		cs = append(cs, proxyChecks(s, env, pub)...)
	}
	if s.IsTLS() && s.HSTS {
		add("info", "HSTS", "browsers will refuse this site over plain HTTP, and for 1 year over a bad certificate")
	}
	return cs
}

func listed(list []string, n string) bool {
	for _, v := range list {
		if strings.EqualFold(v, n) {
			return true
		}
	}
	return false
}

func isLoopbackAddr(addr string) bool {
	h, _, err := net.SplitHostPort(addr)
	if err != nil {
		return false
	}
	if strings.EqualFold(h, "localhost") {
		return true
	}
	ip := net.ParseIP(h)
	return ip != nil && ip.IsLoopback()
}

func ownChecks(s Settings, env CheckEnv, pub *url.URL) []Check {
	var cs []Check
	add := func(status, title, detail string, a ...any) {
		cs = append(cs, Check{Status: status, Title: title, Detail: fmt.Sprintf(detail, a...)})
	}
	var leaf *x509.Certificate
	var err error
	switch {
	case len(env.OwnCertPEM) > 0 || len(env.OwnKeyPEM) > 0:
		_, leaf, err = ParseKeyPair(env.OwnCertPEM, env.OwnKeyPEM)
	case s.Own.CertFile != "" && s.Own.KeyFile != "":
		_, leaf, err = LoadPair(s.Own.CertFile, s.Own.KeyFile)
	default:
		add("error", "Certificate", "paste or upload a certificate chain and key, or give the paths of both files")
		return cs
	}
	if err != nil {
		add("error", "Certificate", "%v", err)
		return cs
	}
	add("ok", "Certificate", "parses, and the key matches")
	switch {
	case env.Now.After(leaf.NotAfter):
		add("error", "Expiry", "expired on %s", leaf.NotAfter.Format("2006-01-02"))
	case env.Now.Before(leaf.NotBefore):
		add("error", "Expiry", "not valid before %s", leaf.NotBefore.Format("2006-01-02"))
	case leaf.NotAfter.Sub(env.Now) < 14*24*time.Hour:
		add("warning", "Expiry", "expires on %s", leaf.NotAfter.Format("2006-01-02"))
	default:
		add("ok", "Expiry", "valid until %s", leaf.NotAfter.Format("2006-01-02"))
	}
	for _, n := range s.Names {
		if !ValidName(n) {
			add("error", "Names", "%q is not a host name or IP address", n)
		} else if leaf.VerifyHostname(n) != nil {
			add("error", "Names", "the certificate does not cover %s (it covers %s)", n, strings.Join(Describe(leaf).Names, ", "))
		}
	}
	if len(s.Names) > 0 {
		add("ok", "Names", "the certificate covers %s", strings.Join(s.Names, ", "))
	}
	if pub != nil {
		if leaf.VerifyHostname(pub.Hostname()) != nil {
			add("error", "Public URL", "the certificate does not cover %s", pub.Hostname())
		} else {
			add("ok", "Public URL", "the certificate covers %s", pub.Hostname())
		}
	}
	if len(s.Names) == 0 {
		// No names asked for: show the ones the certificate itself carries.
		if names := CertNames(leaf); len(names) > 0 {
			add("ok", "Names", "the certificate covers %s", strings.Join(names, ", "))
		} else {
			add("warning", "Names", "the certificate names no host or address; browsers will refuse it")
		}
	}
	if len(env.OwnCertPEM) == 0 && s.Own.CertFile != "" {
		add("info", "Files", "re-read when they change and on SIGHUP")
	}
	return cs
}

func acmeChecks(s Settings, pub *url.URL) []Check {
	var cs []Check
	add := func(status, title, detail string, a ...any) {
		cs = append(cs, Check{Status: status, Title: title, Detail: fmt.Sprintf(detail, a...)})
	}
	if len(s.ACME.Domains) == 0 {
		add("error", "Domains", "list at least one domain name")
	}
	for _, d := range s.ACME.Domains {
		switch {
		case net.ParseIP(d) != nil:
			add("error", "Domains", "%s is an IP address; certificates are issued for names", d)
		case strings.Contains(d, "*"):
			add("error", "Domains", "%s: wildcards need DNS validation, which is not supported", d)
		case !ValidName(d):
			add("error", "Domains", "%q is not a valid domain name", d)
		}
	}
	if pub != nil && !listed(s.ACME.Domains, pub.Hostname()) {
		add("error", "Public URL", "%s is not one of the domains", pub.Hostname())
	}
	if !s.ACME.AcceptTerms {
		add("error", "Terms", "accept the certificate authority's terms of service")
	}
	if u, err := url.Parse(s.ACME.Directory); err != nil || u.Scheme != "https" || u.Host == "" {
		add("error", "Directory URL", "must be an https:// URL")
	} else if s.ACME.Directory == LetsEncryptStaging {
		add("info", "Directory URL", "Let's Encrypt staging: certificates are issued but browsers do not trust them")
	}
	if s.ACME.Email != "" && !strings.Contains(s.ACME.Email, "@") {
		add("error", "Contact e-mail", "%q is not an e-mail address", s.ACME.Email)
	}
	if _, port, err := SplitAddr(s.HTTPSListen); err == nil && port != 443 {
		add("warning", "Port 443", "TLS-ALPN-01 is validated on port 443; forward 443 to %s or issuance fails", s.HTTPSListen)
	}
	if s.HTTPRedirect == "" {
		add("info", "HTTP-01", "no HTTP address set; only TLS-ALPN-01 is offered")
	} else if _, port, err := SplitAddr(s.HTTPRedirect); err == nil && port != 80 {
		add("warning", "Port 80", "HTTP-01 is validated on port 80; forward 80 to %s or only TLS-ALPN-01 works", s.HTTPRedirect)
	}
	add("info", "Issuance", "the certificate is requested on the first HTTPS request for a listed name, or with Request now; it cannot be tested before")
	return cs
}

func proxyChecks(s Settings, env CheckEnv, pub *url.URL) []Check {
	var cs []Check
	add := func(status, title, detail string, a ...any) {
		cs = append(cs, Check{Status: status, Title: title, Detail: fmt.Sprintf(detail, a...)})
	}
	if pub == nil {
		add("error", "Public URL", "required: the address users type, for the Origin check and the snippets")
	}
	trusted, err := ParseProxies(s.TrustedProxies)
	switch {
	case err != nil:
		add("error", "Trusted proxies", "%v", err)
	case len(trusted) == 0:
		add("error", "Trusted proxies", "list the proxy addresses, otherwise X-Forwarded headers are ignored and every user looks like the proxy")
	default:
		for _, p := range trusted {
			if p.Bits() == 0 {
				add("warning", "Trusted proxies", "%s trusts every client to set its own address", p)
			}
		}
		add("ok", "Trusted proxies", "%s", strings.Join(s.TrustedProxies, ", "))
		if env.Peer.IsValid() {
			peerTrusted := false
			for _, p := range trusted {
				peerTrusted = peerTrusted || p.Contains(env.Peer.Unmap())
			}
			switch {
			case peerTrusted && env.ForwardedProto != "":
				add("ok", "Proxy headers", "this request came from trusted %s and carried X-Forwarded-Proto: %s", env.Peer, env.ForwardedProto)
			case peerTrusted:
				add("warning", "Proxy headers", "this request came from trusted %s but without X-Forwarded-Proto", env.Peer)
			default:
				add("info", "Proxy headers", "not tested: this request came directly from %s, not from a trusted proxy", env.Peer)
			}
		}
	}
	if pub != nil && pub.Scheme != "https" {
		add("warning", "Public URL", "is not https; sign-ins are not encrypted between the browser and the proxy")
	}
	if !isLoopbackAddr(s.Listen) {
		add("warning", "HTTP address", "%s is reachable beyond this machine; only the proxies should be able to connect", s.Listen)
	}
	return cs
}
